// 计算生命灵数
export function calculateLifeNumber(year, month, day) {
  // 主命数（命运数）：出生年月日各位数字相加，最终缩减到个位数
  const sum = sumDigits(year) + sumDigits(month) + sumDigits(day);
  const mainNumber = reduceToOneDigit(sum);

  // 天赋数（不缩减到个位的两位数，代表潜在天赋和能力）
  const talentNumber = sum;

  // 内心灵数（灵魂欲望数，简化版用月+日，代表内心真实渴望）
  const innerNumber = reduceToOneDigit(sumDigits(month) + sumDigits(day));

  // 外在灵数（个性表达数，简化版用年+月，代表外在形象和他人印象）
  const outerNumber = reduceToOneDigit(sumDigits(year) + sumDigits(month));

  // 生日数（出生日缩减到个位数，代表天生气质）
  const birthdayNumber = reduceToOneDigit(day);

  // 获取主命数完整解析
  const mainAnalysis = getMainNumberAnalysis(mainNumber);

  return {
    mainNumber, // 主命数/命运数
    talentNumber, // 天赋数
    innerNumber, // 内心灵数/灵魂欲望数
    outerNumber, // 外在灵数/个性表达数
    birthdayNumber, // 生日数
    // 主命数详细解析
    personality: mainAnalysis.personality,
    career: mainAnalysis.career,
    wealth: mainAnalysis.wealth,
    love: mainAnalysis.love,
    health: mainAnalysis.health,
    talent: mainAnalysis.talent,
    lifeLesson: mainAnalysis.lifeLesson,
    // 天赋数解析
    talentAnalysis: getTalentAnalysis(talentNumber),
    // 内心灵数解析
    innerAnalysis: getInnerAnalysis(innerNumber),
    // 外在灵数解析
    outerAnalysis: getOuterAnalysis(outerNumber),
    // 生日数解析
    birthdayAnalysis: getBirthdayAnalysis(birthdayNumber),
  };
}

// 各位数字相加
function sumDigits(num) {
  return num.toString().split('').reduce((sum, d) => sum + parseInt(d), 0);
}

// 缩减到个位数（1-9，特殊的11、22、33保留为卓越数）
function reduceToOneDigit(num) {
  if (num === 11 || num === 22 || num === 33) return num; // 卓越数（Master Numbers）
  while (num > 9) {
    num = sumDigits(num);
  }
  return num;
}

