// 搜索梦境
export function searchDreams(keyword) {
  if (!keyword) return [];
  
  const results = [];
  Object.values(DREAM_LIST).forEach(list => {
    list.forEach(dream => {
      if (dream.title.includes(keyword) || dream.summary.includes(keyword)) {
        results.push(dream);
      }
    });
  });
  return results;
}

// 获取梦境详情（扩展版，会员解锁）
export function getDreamDetail(id) {
  const allDreams = Object.values(DREAM_LIST).flat();
  return allDreams.find(d => d.id === id);
}
