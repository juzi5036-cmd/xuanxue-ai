// 获取字的笔画数
export function getStrokeCount(char) {
  return STROKE_COUNT[char] || Math.floor(Math.random() * 10) + 5; // 找不到的字随机给一个（演示用）
}

// 计算五格
export function calculateWuge(surname, givenName, gender = '男') {
  // 姓氏笔画
  const surnameStrokes = getStrokeCount(surname);
  
  // 名字笔画
  const givenChars = givenName.split('');
  const givenStrokes = givenChars.map(c => getStrokeCount(c));
  
  // 天格 = 姓笔画 + 1（单姓）
  const tianGe = surnameStrokes + 1;
  
  // 人格 = 姓笔画 + 名字第一个字笔画
  const renGe = surnameStrokes + givenStrokes[0];
  
  // 地格 = 名字笔画总和（双字名）或 名字笔画 + 1（单字名）
  let diGe;
  if (givenStrokes.length === 2) {
    diGe = givenStrokes[0] + givenStrokes[1];
  } else {
    diGe = givenStrokes[0] + 1;
  }
  
  // 外格 = 总格 - 人格 + 1（单姓双名）
  const zongGe = surnameStrokes + givenStrokes.reduce((a, b) => a + b, 0);
  const waiGe = zongGe - renGe + 1;
  
  // 五格吉凶判断
  const wuge = {
    tianGe: { value: tianGe, luck: getLuckLevel(tianGe) },
    renGe: { value: renGe, luck: getLuckLevel(renGe) },
    diGe: { value: diGe, luck: getLuckLevel(diGe) },
    waiGe: { value: waiGe, luck: getLuckLevel(waiGe) },
    zongGe: { value: zongGe, luck: getLuckLevel(zongGe) },
  };
  
  // 总分（基于五格吉凶）
  let totalScore = 0;
  const luckScores = { '吉': 20, '半吉': 15, '凶': 5, '大凶': 0 };
  Object.values(wuge).forEach(ge => {
    totalScore += luckScores[ge.luck] || 10;
  });
  
  // 基础分
  totalScore += Math.floor(Math.random() * 20) + 50; // 演示用，实际应有完整算法
  totalScore = Math.min(100, Math.max(50, totalScore));
  
  return {
    surname,
    givenName,
    fullName: surname + givenName,
    gender,
    wuge,
    totalScore,
    summary: getScoreSummary(totalScore),
    characterAnalysis: getCharacterAnalysis(wuge.renGe.value, gender),
  };
}

// 吉凶等级判断（81数理）
export function getLuckLevel(num) {
  const n = num % 81 || 81;
  const lucky = [1, 3, 5, 6, 7, 8, 11, 13, 15, 16, 17, 18, 21, 23, 24, 25, 29, 31, 32, 33, 35, 37, 39, 41, 45, 47, 48, 52, 55, 57, 61, 63, 65, 67, 68, 81];
  const halfLucky = [6, 17, 26, 27, 28, 38, 40, 42, 43, 44, 49, 50, 51, 53, 58, 71, 73, 75, 77, 78];
  const unlucky = [2, 4, 9, 10, 12, 14, 19, 20, 22, 28, 34, 36, 40, 46, 49, 54, 56, 59, 60, 62, 64, 66, 69, 70, 72, 74, 76, 79, 80];
  
  if (lucky.includes(n)) return '吉';
  if (halfLucky.includes(n)) return '半吉';
  return '凶';
}

// 评分总结
export function getScoreSummary(score) {
  if (score >= 90) return '名字非常好，五格俱佳，运势亨通';
  if (score >= 80) return '名字很好，格局优良，诸事顺遂';
  if (score >= 70) return '名字不错，基础扎实，稳步发展';
  if (score >= 60) return '名字一般，有吉有凶，需努力弥补';
  return '名字欠佳，建议改名以改运';
}

